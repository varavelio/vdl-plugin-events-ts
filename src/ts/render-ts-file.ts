import { listPlaceholderMatches } from "../events/placeholders.js";
import type { EventModel } from "../models/event-model.js";
import { renderSubjectValue, renderTypeScriptType } from "./render-ts-type.js";

/**
 * Renders the consolidated TypeScript output file for all collected events.
 */
export function renderTsFile(events: EventModel[]): string {
  const lines: string[] = ["// Generated by VDL. Do not edit.", ""];

  if (events.length > 0) {
    lines.push(
      ...renderCatalogInterface(events),
      "",
      ...renderCatalogValue(events),
    );
  }

  return `${lines.join("\n")}\n`;
}

/**
 * Renders the generated event catalog interface with typed buildSubject fields.
 */
function renderCatalogInterface(events: EventModel[]): string[] {
  const lines = [
    "/**",
    " * Catalogs all `@event`-annotated types with their subject metadata and builders.",
    " */",
    "export interface VDLEventCatalog {",
  ];

  for (const event of events) {
    lines.push(...renderCatalogEntryDoc(event, "  "));
    lines.push(`  ${event.name}: {`);
    lines.push(`    /** Event name: \`${event.name}\` */`);
    lines.push("    name: string;");
    lines.push(`    /** Event subject: \`${event.subjectTemplate}\` */`);
    lines.push("    subjectTemplate: string;");
    lines.push(
      `    /** Event subject builder: \`${event.subjectTemplate}\` */`,
    );
    lines.push(`    buildSubject: (${renderSubjectParams(event)}) => string;`);
    lines.push("  };");
  }

  lines.push("}");
  return lines;
}

/**
 * Renders the generated event catalog value with inline subject builders.
 */
function renderCatalogValue(events: EventModel[]): string[] {
  const lines = [
    "/**",
    " * Indexes generated events by payload type name.",
    " */",
    "export const VDLEvents: VDLEventCatalog = {",
  ];

  for (const event of events) {
    lines.push(...renderCatalogEntryDoc(event, "  "));
    lines.push(`  ${event.name}: {`);
    lines.push(`    /** Event name: \`${event.name}\` */`);
    lines.push(`    name: ${JSON.stringify(event.name)},`);
    lines.push(`    /** Event subject: \`${event.subjectTemplate}\` */`);
    lines.push(
      `    subjectTemplate: ${JSON.stringify(event.subjectTemplate)},`,
    );
    lines.push(
      `    /** Event subject builder: \`${event.subjectTemplate}\` */`,
    );
    lines.push(`    buildSubject(${renderSubjectParams(event)}): string {`);
    lines.push(`      return ${renderSubjectExpression(event)};`);
    lines.push("    },");
    lines.push("  },");
  }

  lines.push("};");
  return lines;
}

/**
 * Renders JSDoc for one catalog entry.
 */
function renderCatalogEntryDoc(event: EventModel, indent: string): string[] {
  const lines = [
    `${indent}/**`,
    `${indent} * Metadata for the \`${event.name}\` event.`,
    `${indent} *`,
    `${indent} * Subject: \`${event.subjectTemplate}\``,
  ];

  if (event.isDeprecated) {
    lines.push(
      `${indent} *`,
      `${indent} * @deprecated ${event.deprecationMessage ?? "This event is deprecated."}`,
    );
  }

  lines.push(`${indent} */`);
  return lines;
}

/**
 * Renders the parameter list string for a subject builder function.
 */
function renderSubjectParams(event: EventModel): string {
  return event.placeholders
    .map((placeholder) => {
      return `${placeholder.field}: ${renderTypeScriptType(placeholder.primitiveType)}`;
    })
    .join(", ");
}

/**
 * Renders the expression that composes one event subject string.
 */
function renderSubjectExpression(event: EventModel): string {
  const placeholdersByName = new Map(
    event.placeholders.map((placeholder) => [placeholder.field, placeholder]),
  );
  let cursor = 0;
  let literalChunk = "";
  let expression = "";

  for (const match of listPlaceholderMatches(event.subjectTemplate)) {
    const start = match.index ?? 0;
    const raw = match[0] ?? "";
    const placeholderName = match[1] ?? "";
    literalChunk += event.subjectTemplate.slice(cursor, start);

    const placeholder = placeholdersByName.get(placeholderName);
    if (!placeholder) {
      throw new Error(`Missing placeholder model for ${placeholderName}`);
    }

    expression += `${escapeTemplateText(literalChunk)}\${${renderSubjectValue(placeholder.field, placeholder.primitiveType)}}`;
    literalChunk = "";
    cursor = start + raw.length;
  }

  literalChunk += event.subjectTemplate.slice(cursor);

  if (expression === "") {
    return JSON.stringify(event.subjectTemplate);
  }

  return `\`${expression}${escapeTemplateText(literalChunk)}\``;
}

/**
 * Escapes static subject text for safe interpolation inside a template literal.
 */
function escapeTemplateText(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}
